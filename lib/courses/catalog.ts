function outlinedLesson(
  moduleId: string,
  id: string,
  title: string,
  summary: string,
  durationMinutes: number,
  objectives: string[],
): Lesson {
  return {
    id,
    moduleId,
    title,
    summary,
    durationMinutes,
    objectives,
    status: "outlined",
  };
}

